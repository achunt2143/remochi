// Writes ./report/README.md from ./report/results.json (written by the diff
// page) and the context snapshots.
//   node scripts/nubbin-diff/report.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, 'report');

export function writeReport() {
  const results = JSON.parse(readFileSync(join(dir, 'results.json'), 'utf8'));
  const pct = (n) => `${n.toFixed(2)}%`;
  const rows = results.map(
    (r) => `| \`${r.id}\` | ${r.theme} | ${r.scale}× | ${r.w}×${r.h} | ${pct(r.mismatch)} | ${pct(r.shifted)} | ${pct(r.mean)} | ![](${r.crop}) |`
  );
  const jointsFile = join(dir, 'joints.json');
  const joints = existsSync(jointsFile) ? JSON.parse(readFileSync(jointsFile, 'utf8')) : null;
  const jointRows = joints
    ? joints.results.map((j) => `| ${j.placement} | ${j.joint} | ${j.scale}× | ${j.step.toFixed(3)} | ${j.centreShift.toFixed(3)} | ${j.ok ? 'ok' : '**FAIL**'} |`)
    : [];
  const selfTest = joints
    ? Object.entries(joints.selfTest).map(([scale, byOffset]) =>
        `${scale}×: ${Object.entries(byOffset).map(([o, steps]) => `${o}px → ${Math.max(...steps).toFixed(2)}px`).join(', ')}`)
    : [];
  const context = ['popups', 'corners', 'grabber', 'static', 'halo'].flatMap((view) =>
    ['light', 'dark']
      .filter((theme) => existsSync(join(dir, `context/${view}-${theme}-2x.png`)))
      .map((theme) => `### ${view}, ${theme}\n\n![${view} ${theme}](context/${view}-${theme}-2x.png)\n`)
  );
  writeFileSync(
    join(dir, 'README.md'),
    `# Drawn nubbins vs. sprites

Generated by \`npm run nubbin-diff\` (see \`scripts/nubbin-diff/\`). Each
sprite is rendered next to its drawing (\`src/shared/nubbin.jsx\`) at 1× and
2×, composited over the theme background, in the sprite's own colours.

- **mismatch**: pixels where any channel differs by more than 16/255.
- **shape**: the same, but a pixel only counts if no sprite pixel within
  1px matches it either. At 2× the sprite is a 1× PNG upscaled (blurred)
  while the drawing is crisp, so raw mismatch there is mostly edge blur;
  this column is what's left once soft or sub-pixel-shifted edges are
  forgiven.
- **mean**: mean absolute difference.

Crops: sprite | drawing | difference (red/yellow over threshold, grey
under), magnified 8× per CSS pixel.

## Deliberate differences

Places where the drawing doesn't copy the sprite because the sprite was off:

- **Popup colours.** The light sprites fill the bump white (#fff) on a
  #f5f5f5 panel; the dark ones use stroke #646464 / fill #2a2a2a on a panel
  with a #333 border and #404040 background. The drawn bump uses the
  panel's own border and background tokens, so it matches the panel in
  both themes. (The table compares shapes in the sprites' colours.)
- **Divider in dark.** div-left/right.png are an opaque light-grey groove
  with no dark copy, so they showed as a bright stripe on dark surfaces
  (the 100% rows below). The drawn groove is the popup border colour at the
  sprite's per-row opacities, which reproduces the sprite over light
  backgrounds and becomes a subtle groove over dark ones.
- **Vertical Divider.** The old caps stretched the horizontal 320×4 PNG
  into a tall, thin box, so the groove ran across the line and the taper
  along its width. The drawn caps turn with the orientation.
- **Repanel grabber colours.** The shadow variant (and dark mode) used
  left-shadow.png, a #3f3f3f/#383838 shape, even on the light shadow panel
  (#f5f5f5). The drawn grabber uses the panel's border token and the
  variant's own background token: identical to left.png for light default
  panels, near-identical (#404040/#333) for dark default ones.
- **Shadow tails.** The sprites' soft shadow stopped dead at the box edge,
  which shows as a step where a corner cap meets the line. The drawn shadow
  fades out over the last stretch instead.
- **Sizes.** down.png is 72px wide where every other bump is 71; Popup's
  box was always 71, so the drawing is 71.
- **Corner ramp end.** The sprites' corner ramp was still settling onto the
  line in the last 2–3px of its box, a slight kink where the border carries
  on. The drawn ramp is pinned to land 2px before the end, which costs
  about a point of shape mismatch on the corner rows below.
- **Corner caps over round corners.** PopupPanel's panel has the uniform 24px
  field corner and squares the corner a cap sits on, as Mochi does. The cap
  still takes that corner's radius from the panel's computed style (0 here)
  and, given a round one, reaches over the curve to meet the straight
  border. The sprites (square corners) are unchanged at radius 0, so the
  table above is the same; the joint check below runs all 8 corner
  placements.
- **Repanel grabber edge.** The component's grabber is as thick as the
  pane's left edge (\`--mochi-pane-edge-width\`, 1px by default) and in the
  pane-edge colour. The table still compares the 2px nubbin against the
  sprite, which is the shape check; the joint check below measures the real
  grabber at 1px and 2px edges.
- **Popup on whole pixels.** Not a sprite difference but the cause of the
  one seam review found: the far-side nubbins sit at \`left/top: 100%\` of
  a panel sized by its content, and when that size was fractional the
  border and the nubbin could snap to device pixels differently (a 0.25–0.4px
  step, worst on the right-pointing nub). PopupPanel now rounds its
  position and rounds its size up by under a pixel, so there's nothing to
  snap. See the joint check below.

| sprite | theme | scale | size | mismatch | shape | mean | crop |
|---|---|---|---|---|---|---|---|
${rows.join('\n')}

## Joints

The per-sprite table compares each nubbin on its own, so it can't see
whether a popup nubbin's line lines up with the border it runs on from. This
check samples the stroke 0.5–2.5px either side of each place a popup
nubbin's line meets the panel's straight border (both ends of a bump; the
line end and the side of a corner cap) and finds the stroke's two edges
across the line. **step** is the largest edge step between border and
nubbin, which fails over ${joints ? joints.tolerance : '–'}px; **centre** is how far the
stroke's centre moves. (Where the border runs on behind the nubbin, an
offset of d widens the line, so the centre only moves d/2.)

${joints ? `Source: ${joints.source}.` : 'Not run yet.'}

| placement | joint | scale | step (px) | centre (px) | |
|---|---|---|---|---|---|
${jointRows.join('\n')}

Self-test (the check on a painted border with a tail offset by a known
amount): ${selfTest.join('; ')}.

## Shadow panel grabber

\`Repanel style="shadow"\` paints an inset halo on its own box, so it used
to stop at the straight edge and the grabber read as a flat patch. The
shadow grabber now redraws the halo over the panel's bottom-left corner as
the same inset shadow (offset 4px, blur sigma 25px, the tint token) of the
panel's outline *including* the bump, fading into the CSS halo over its
last 30px so there's no line where they meet (measured: 0–1 levels of 255
across the hand-over, the rounding floor). The default variant is
untouched (0 pixels differ).

Shadow grabber, 4× (before | after | after, inside a RepanelStack):

![shadow grabber, light](halo/shadow-grabber-light.png)

![shadow grabber, dark](halo/shadow-grabber-dark.png)

Default grabber for reference, unchanged (standalone | in a stack):

![default grabber, light](halo/default-grabber-light.png)
![default grabber, dark](halo/default-grabber-dark.png)

## In context

Snapshots of \`context.html\` (SVG foreignObject, so text uses a fallback
font).

${context.join('\n')}`
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) writeReport();
